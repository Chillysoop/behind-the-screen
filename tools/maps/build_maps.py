"""Compile the map library: every spec in game/data/maps/*.map becomes a board in the generated
game/data/map_library.lua (the boards.lua shape plus adventure, order, source, credit, about, tags
and places: the spec's spots), after
checking it: kinds the kit has, pieces on the mat and not standing in each other, starts and spots
on free squares, the party able to reach the foes and kept inside the walls, enough room to fight.
game/data/boards.lua adds the library's boards to its own.

    python3 tools/maps/build_maps.py             check and write the library
    python3 tools/maps/build_maps.py --check     check only (exit 1 on a problem)
    python3 tools/maps/build_maps.py --lenient   while new pieces are on their way into the kit:
                                                 accept the kinds in mapspec.EXPECTED (with a
                                                 warning) at the footprints they were promised
    python3 tools/maps/build_maps.py --print ID  print one board as text (what blocks, starts, spots)

The format is in tools/maps/README.md.
"""
import argparse
import glob
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import mapspec as ms  # noqa: E402

HEADER = """-- Generated by tools/maps/build_maps.py from game/data/maps/*.map. Don't edit by hand: change the
-- spec and rerun it. The map library: boards drawn from the adventures' own maps, in the shape of
-- game/data/boards.lua (which adds them to its boards), plus
--   adventure  which adventure the map belongs to; order: where it comes in that adventure;
--              room: the adventure's own id for the room (the museum's module.lua rooms)
--   source     "adventure" (drawn after the adventure's own map) or "imported" (the importer's
--              first pass, not finished by hand); credit: whose map it follows
--   about      a short line for the map library; tags: what kind of place it is
--   places     the places in the room worth going to (the spec's spots): { id (the book's key),
--              x, y, name, line, near = { ids of the features beside it } }. Not board.compile's
--              spots, which are squares a hero walks to when a feature drops in.
-- order = { ids }: every board in library order (by adventure, then order).
"""


def text_board(b):
    """A board as text: what each square holds (capitals block), starts and spots."""
    grid = [["." for _ in range(ms.W)] for _ in range(ms.H)]
    for (x, y) in b["outside"]:
        grid[y - 1][x - 1] = " "
    for pc in b["pieces"]:
        pass
    rows = []
    for y in range(1, ms.H + 1):
        row = ""
        for x in range(1, ms.W + 1):
            ch = grid[y - 1][x - 1]
            if (x, y) in b["blocked"]:
                ch = "#"
            if (x, y) == tuple(b["party"]):
                ch = "P"
            elif (x, y) == tuple(b["foes"]):
                ch = "F"
            elif (x, y) == tuple(b["npc"]):
                ch = "N"
            for i, s in enumerate(b["spots"]):
                if (s["x"], s["y"]) == (x, y):
                    ch = "abcdefghijklmnopqrstuvwxyz"[i % 26]
            row += ch + " "
        rows.append("  " + row)
    out = [f"{b['id']}: {b['title']}"] + rows
    for i, s in enumerate(b["spots"]):
        out.append(f"  {'abcdefghijklmnopqrstuvwxyz'[i % 26]} {s['id']:>4} {s['name']}: {s['line']}")
    return "\n".join(out)


def build(strict=True, check_only=False, show=None, maps_dir=ms.MAPS_DIR, out_path=ms.LIBRARY):
    kit_raw = ms.load_kit()
    kit, pending = ms.kit_with_expected(kit_raw, strict=strict)
    paths = sorted(glob.glob(os.path.join(maps_dir, "*.map")))
    problems, warnings = [], []
    boards = []
    hand_made = ms.board_ids_in_boards_lua()
    foreign = ms.foreign_words()
    seen_ids = {}
    for p in paths:
        try:
            spec = ms.read(p)
        except ms.SpecError as e:
            problems.append(str(e))
            continue
        b, probs, warns = ms.compile_spec(spec, kit)
        problems += probs
        warnings += warns
        if not b:
            continue
        name = os.path.basename(p)
        if b["id"] in seen_ids:
            problems.append(f"{name}: id {b['id']} is also used by {seen_ids[b['id']]}")
        seen_ids[b["id"]] = name
        if b["id"] in hand_made:
            problems.append(f"{name}: id {b['id']} is already a board in game/data/boards.lua")
        if os.path.splitext(name)[0] != b["id"]:
            warnings.append(f"{name}: the file isn't named after its id ({b['id']}.map)")
        # What the table hears mustn't bring in another story's words (the museum is strictly the book).
        if b["adventure"] == "museum":
            said = [b["title"], b["about"]] + [s["name"] + " " + s["line"] for s in b["spots"]]
            for f in b["features"]:
                said.append(f["say"] or kit[f["parts"][0]["kind"]].get("say", ""))
            for t in said:
                for w in foreign:
                    if re.search(r"(?<![\w])" + re.escape(w) + r"(?![\w])", t):
                        problems.append(f"{name}: {w!r} belongs to another story: {t!r}")
        boards.append(b)
    if pending and not strict:
        warnings.insert(0, f"{len(pending)} expected kinds aren't in game/data/props.lua yet: {', '.join(pending)}")
    seen = set()
    for w in warnings:
        if w not in seen:
            print("  warning:", w)
            seen.add(w)
    if problems:
        for p in problems:
            print("  " + p)
        print(f"  [FAIL] The map library  -  {len(problems)} problems in {len(paths)} specs")
        return 1
    boards.sort(key=lambda b: (b["adventure"], b["order"], b["id"]))
    if show:
        for b in boards:
            if b["id"] == show:
                print(text_board(b))
                return 0
        print(f"no board {show}")
        return 1
    lua = [HEADER, "local L = {}", "", "L.boards = {"]
    for b in boards:
        lua.append(ms.board_lua(b))
    lua.append("}")
    lua.append("")
    lua.append("L.order = { " + ", ".join(ms.lua_str(b["id"]) for b in boards) + " }")
    lua.append("")
    lua.append("return L")
    text = "\n".join(lua) + "\n"
    if not check_only:
        old = open(out_path, encoding="utf-8").read() if os.path.exists(out_path) else None
        if old != text:
            with open(out_path, "w", encoding="utf-8", newline="\n") as f:
                f.write(text)
            print(f"  wrote {os.path.relpath(out_path, ms.ROOT)}")
    spots = sum(len(b["spots"]) for b in boards)
    print(f"  [PASS] The map library: {len(boards)} boards, {spots} places, on the mat, nothing overlapping, "
          f"starts and spots free, the way through open, the walls closed")
    return 0


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true", help="check only, don't write the library")
    ap.add_argument("--lenient", action="store_true", help="accept expected kinds that aren't in game/data/props.lua yet")
    ap.add_argument("--strict", action="store_true", help=argparse.SUPPRESS)       # the default now
    ap.add_argument("--print", dest="show", metavar="ID", help="print one board as text")
    a = ap.parse_args()
    sys.exit(build(strict=not a.lenient, check_only=a.check or bool(a.show), show=a.show))


if __name__ == "__main__":
    main()
