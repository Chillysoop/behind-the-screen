def lua_layout():
    out = ["-- Generated by tools/generate.py from tools/terrain_layout.py. Don't edit by hand.",
           "-- Squares each terrain set covers on the 20 x 13 battle mat (x west to east, y north to south).",
           "", "return {", f"    W = {GRID_W}, H = {GRID_H},", "    sets = {"]
    for name, s in SETS.items():
        blocked = []
        for (_, squares) in s["pieces"]:
            blocked.extend(squares)
        blocked = sorted(set(blocked))
        sq = ", ".join(f"{{ {x}, {y} }}" for (x, y) in blocked)
        # Points of interest: open squares next to each piece, where a mini goes to poke at it.
        bset = set(blocked)
        spots = []
        for (_, squares) in s["pieces"]:
            for (x, y) in squares[:1]:
                for (dx, dy) in ((0, 1), (1, 0), (-1, 0), (0, -1), (1, 1), (-1, 1)):
                    nx, ny = x + dx, y + dy
                    if 2 <= nx <= GRID_W - 1 and 2 <= ny <= GRID_H - 1 and (nx, ny) not in bset:
                        spots.append((nx, ny))
                        break
        spots = sorted(set(spots))
        sp = ", ".join(f"{{ {x}, {y} }}" for (x, y) in spots)
        out.append(f'        {name} = {{ title = "{s["title"]}", light = "{s["light"]}",')
        out.append(f"            party = {{ {s['party'][0]}, {s['party'][1]} }}, npc = {{ {s['npc'][0]}, {s['npc'][1]} }}, "
                   f"foes = {{ {s['foes'][0]}, {s['foes'][1]} }},")
        out.append(f"            blocked = {{ {sq} }},")
        out.append(f"            spots = {{ {sp} }} }},")
    out.append("    },")
    out.append("}")
    return "\n".join(out) + "\n"
