        for i, (x, top) in enumerate([(56, 30), (80, 14), (104, 18), (128, 36)]):
            d.rounded_rectangle(box(x, top, x + 20, 112), radius=10 * k, fill=255)
        thumb = [(54, 132), (24, 92), (36, 80), (70, 112)]
        d.polygon(P(thumb), fill=255)
