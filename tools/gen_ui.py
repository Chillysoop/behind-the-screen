"""UI assets for the greybox screens: GUI fonts, glyph metrics for text wrapping,
and the atlas images (rounded panel, dot, and the status bar icons).

    python3 tools/gen_ui.py      (also run by tools/generate.py)
"""
import math

import numpy as np
from PIL import Image, ImageDraw, ImageFont

from gen_common import path, to_img, smoothstep, FONTS

# name -> (ttf, size). Sizes are pixels at the 1600x900 reference resolution.
GUI_FONTS = {
    "ui14": ("Outfit-Regular.ttf", 15),
    "ui18": ("Outfit-Regular.ttf", 18),
    "ui18b": ("Outfit-Bold.ttf", 18),
    "ui22b": ("Outfit-Bold.ttf", 22),
    "title30": ("Lora-Bold.ttf", 30),
    "hand24": ("NothingYouCouldDo-Regular.ttf", 24),
    "story22": ("Lora-Bold.ttf", 22),
}

FONT_TEMPLATE = ('font: "/assets/fonts/{ttf}"\nmaterial: "/builtins/fonts/font.material"\nsize: {size}\n'
                 'antialias: 1\nalpha: 1.0\noutline_alpha: 0.0\noutline_width: 0.0\nshadow_alpha: 0.0\n'
                 'output_format: TYPE_BITMAP\n')


def fonts_and_metrics():
    lua = ["-- Generated by tools/gen_ui.py: glyph advances (pixels) for wrapping GUI text.",
           "-- Characters outside printable ASCII count as a space.", "", "return {"]
    for name, (ttf, size) in GUI_FONTS.items():
        with open(path("assets/fonts", name + ".font"), "w", newline="\n") as f:
            f.write(FONT_TEMPLATE.format(ttf=ttf, size=size))
        font = ImageFont.truetype(f"{FONTS}/{ttf}", size)
        ascent, descent = font.getmetrics()
        adv = []
        for code in range(32, 127):
            adv.append(round(font.getlength(chr(code)), 2))
        lua.append(f"    {name} = {{")
        lua.append(f"        line = {ascent + descent},")
        lua.append(f"        ascent = {ascent},")
        lua.append("        adv = { " + ", ".join(repr(a) for a in adv) + " },")
        lua.append("    },")
    lua.append("}")
    with open(path("game/ui/metrics.lua"), "w", newline="\n") as f:
        f.write("\n".join(lua) + "\n")


def panel():
    """White rounded rectangle for slice-9 panels (radius 10 in a 40x40 image)."""
    s, r = 40, 10
    y, x = np.mgrid[0:s, 0:s].astype(float) + 0.5
    cx = np.clip(x, r, s - r)
    cy = np.clip(y, r, s - r)
    d = np.sqrt((x - cx) ** 2 + (y - cy) ** 2)
    a = smoothstep(r + 0.5, r - 0.8, d)
    to_img(np.ones((s, s, 3)), a).save(path("assets/ui", "panel.png"))


def dot():
    s = 32
    y, x = np.mgrid[0:s, 0:s].astype(float) + 0.5
    d = np.sqrt((x - s / 2) ** 2 + (y - s / 2) ** 2)
    a = smoothstep(s / 2, s / 2 - 1.5, d)
    to_img(np.ones((s, s, 3)), a).save(path("assets/ui", "dot.png"))


# Status icons: white on transparent, tinted in the GUI. Drawn at 4x and scaled down.
ICON_SIZE = 48
ICON_NAMES = ["spotlight", "challenge", "story", "social", "reward", "fun", "commitment", "investment",
              "trust", "suspicion", "up", "down", "warn", "empathy", "mood", "d20", "heart", "clock", "tail", "speed",
              "hourglass"]


def _icon_canvas():
    big = ICON_SIZE * 4
    img = Image.new("L", (big, big), 0)
    return img, ImageDraw.Draw(img), big


def _star(d, cx, cy, r_out, r_in, points=5, rot=-90):
    pts = []
    for i in range(points * 2):
        r = r_out if i % 2 == 0 else r_in
        a = math.radians(rot + i * 180 / points)
        pts.append((cx + r * math.cos(a), cy + r * math.sin(a)))
    d.polygon(pts, fill=255)


def draw_icon(name):
    img, d, S = _icon_canvas()
    c = S / 2
    if name == "spotlight":
        _star(d, c, c + 6, S * 0.47, S * 0.2)
    elif name == "challenge":
        # A sword, point up, then turned 45 degrees.
        sw = Image.new("L", (S, S), 0)
        sd = ImageDraw.Draw(sw)
        sd.polygon([(c, S * 0.04), (c + 14, S * 0.16), (c + 14, S * 0.66), (c - 14, S * 0.66), (c - 14, S * 0.16)], fill=255)
        sd.rounded_rectangle([c - 52, S * 0.66, c + 52, S * 0.66 + 20], radius=8, fill=255)
        sd.rectangle([c - 10, S * 0.66 + 20, c + 10, S * 0.9], fill=255)
        sd.ellipse([c - 18, S * 0.88, c + 18, S * 0.88 + 36], fill=255)
        img = sw.rotate(-45, resample=Image.BICUBIC, center=(c, c))
        d = ImageDraw.Draw(img)
    elif name == "story":
        # An open book.
        d.polygon([(S * 0.06, S * 0.24), (S * 0.47, S * 0.3), (S * 0.47, S * 0.84), (S * 0.06, S * 0.76)], fill=255)
        d.polygon([(S * 0.94, S * 0.24), (S * 0.53, S * 0.3), (S * 0.53, S * 0.84), (S * 0.94, S * 0.76)], fill=255)
        for k in range(3):
            y = S * (0.4 + k * 0.12)
            d.line([(S * 0.14, y), (S * 0.39, y + 8)], fill=0, width=9)
            d.line([(S * 0.86, y), (S * 0.61, y + 8)], fill=0, width=9)
    elif name == "social":
        d.rounded_rectangle([S * 0.06, S * 0.12, S * 0.94, S * 0.7], radius=S * 0.16, fill=255)
        d.polygon([(S * 0.24, S * 0.62), (S * 0.46, S * 0.66), (S * 0.18, S * 0.92)], fill=255)
        for k in range(3):
            x = S * (0.3 + k * 0.2)
            d.ellipse([x - 16, S * 0.41 - 16, x + 16, S * 0.41 + 16], fill=0)
    elif name == "reward":
        top, mid, bot = S * 0.16, S * 0.38, S * 0.9
        d.polygon([(S * 0.28, top), (S * 0.72, top), (S * 0.95, mid), (c, bot), (S * 0.05, mid)], fill=255)
        d.line([(S * 0.05, mid), (S * 0.95, mid)], fill=0, width=10)
        d.line([(S * 0.36, mid), (c, bot)], fill=0, width=8)
        d.line([(S * 0.64, mid), (c, bot)], fill=0, width=8)
    elif name == "fun":
        d.ellipse([S * 0.06, S * 0.06, S * 0.94, S * 0.94], fill=255)
        d.ellipse([S * 0.3, S * 0.3, S * 0.4, S * 0.44], fill=0)
        d.ellipse([S * 0.6, S * 0.3, S * 0.7, S * 0.44], fill=0)
        d.arc([S * 0.24, S * 0.3, S * 0.76, S * 0.76], start=20, end=160, fill=0, width=18)
    elif name == "commitment":
        # A calendar page: showing up every week.
        d.rounded_rectangle([S * 0.08, S * 0.16, S * 0.92, S * 0.92], radius=22, fill=255)
        d.rectangle([S * 0.16, S * 0.38, S * 0.84, S * 0.84], fill=0)
        for k in range(3):
            for j in range(2):
                x = S * (0.24 + k * 0.26)
                y = S * (0.47 + j * 0.2)
                d.rounded_rectangle([x, y, x + S * 0.14, y + S * 0.13], radius=6, fill=255)
        d.rounded_rectangle([S * 0.26, S * 0.04, S * 0.34, S * 0.26], radius=8, fill=255)
        d.rounded_rectangle([S * 0.66, S * 0.04, S * 0.74, S * 0.26], radius=8, fill=255)
    elif name == "investment":
        r = S * 0.24
        d.ellipse([S * 0.06, S * 0.12, S * 0.06 + 2 * r, S * 0.12 + 2 * r], fill=255)
        d.ellipse([S * 0.94 - 2 * r, S * 0.12, S * 0.94, S * 0.12 + 2 * r], fill=255)
        d.polygon([(S * 0.075, S * 0.44), (S * 0.925, S * 0.44), (c, S * 0.92)], fill=255)
    elif name == "trust":
        d.polygon([(c, S * 0.04), (S * 0.9, S * 0.18), (S * 0.86, S * 0.56), (c, S * 0.96), (S * 0.14, S * 0.56),
                   (S * 0.1, S * 0.18)], fill=255)
        d.line([(S * 0.32, S * 0.5), (S * 0.46, S * 0.64), (S * 0.7, S * 0.36)], fill=0, width=20, joint="curve")
    elif name == "suspicion":
        # An eye.
        pts = []
        for i in range(0, 361, 6):
            a = math.radians(i)
            x = c + S * 0.46 * math.cos(a)
            y = c + S * 0.28 * math.sin(a) * (abs(math.cos(a)) ** 0.0) * (1 - 0.35 * abs(math.cos(a)))
            pts.append((x, y))
        d.polygon(pts, fill=255)
        d.ellipse([c - S * 0.17, c - S * 0.17, c + S * 0.17, c + S * 0.17], fill=0)
        d.ellipse([c - S * 0.08, c - S * 0.08, c + S * 0.08, c + S * 0.08], fill=255)
    elif name == "up":
        d.polygon([(c, S * 0.14), (S * 0.9, S * 0.78), (S * 0.1, S * 0.78)], fill=255)
    elif name == "down":
        d.polygon([(c, S * 0.86), (S * 0.9, S * 0.22), (S * 0.1, S * 0.22)], fill=255)
    elif name == "warn":
        d.polygon([(c, S * 0.04), (S * 0.97, S * 0.92), (S * 0.03, S * 0.92)], fill=255)
        d.rounded_rectangle([c - 12, S * 0.3, c + 12, S * 0.64], radius=10, fill=0)
        d.ellipse([c - 14, S * 0.71, c + 14, S * 0.71 + 28], fill=0)
    elif name == "empathy":
        # A mood ring.
        d.ellipse([S * 0.06, S * 0.2, S * 0.94, S * 0.96], fill=255)
        d.ellipse([S * 0.2, S * 0.34, S * 0.8, S * 0.82], fill=0)
        d.ellipse([c - S * 0.2, S * 0.02, c + S * 0.2, S * 0.36], fill=255)
    elif name == "mood":
        # A little sun: how they walk in this week.
        d.ellipse([c - S * 0.22, c - S * 0.22, c + S * 0.22, c + S * 0.22], fill=255)
        for k in range(8):
            a = math.radians(k * 45)
            d.line([(c + S * 0.31 * math.cos(a), c + S * 0.31 * math.sin(a)),
                    (c + S * 0.46 * math.cos(a), c + S * 0.46 * math.sin(a))], fill=255, width=18)
    elif name == "d20":
        # A die seen face-on: a hexagon with a raised triangle face.
        pts = [(c + S * 0.47 * math.cos(math.radians(90 + k * 60)), c + S * 0.47 * math.sin(math.radians(90 + k * 60)))
               for k in range(6)]
        d.polygon(pts, fill=255)
    elif name == "heart":
        r = S * 0.24
        d.ellipse([S * 0.06, S * 0.12, S * 0.06 + 2 * r, S * 0.12 + 2 * r], fill=255)
        d.ellipse([S * 0.94 - 2 * r, S * 0.12, S * 0.94, S * 0.12 + 2 * r], fill=255)
        d.polygon([(S * 0.075, S * 0.44), (S * 0.925, S * 0.44), (c, S * 0.92)], fill=255)
    elif name == "clock":
        d.ellipse([S * 0.06, S * 0.06, S * 0.94, S * 0.94], fill=255)
        d.ellipse([S * 0.16, S * 0.16, S * 0.84, S * 0.84], fill=0)
        d.line([(c, c), (c, S * 0.26)], fill=255, width=16)
        d.line([(c, c), (S * 0.7, S * 0.6)], fill=255, width=16)
    elif name == "tail":
        # Speech-bubble tail: a soft triangle pointing down.
        d.polygon([(0, 0), (S, 0), (c, S)], fill=255)
    elif name == "speed":
        for k in range(2):
            x0 = S * (0.1 + k * 0.4)
            d.polygon([(x0, S * 0.18), (x0 + S * 0.42, c), (x0, S * 0.82)], fill=255)
    elif name == "hourglass":
        d.rectangle([S * 0.16, S * 0.04, S * 0.84, S * 0.14], fill=255)
        d.rectangle([S * 0.16, S * 0.86, S * 0.84, S * 0.96], fill=255)
        d.polygon([(S * 0.22, S * 0.14), (S * 0.78, S * 0.14), (c + 10, c), (S * 0.78, S * 0.86), (S * 0.22, S * 0.86),
                   (c - 10, c)], fill=255)
    alpha = img.resize((ICON_SIZE, ICON_SIZE), Image.LANCZOS)
    out = Image.new("RGBA", (ICON_SIZE, ICON_SIZE), (255, 255, 255, 0))
    out.putalpha(alpha)
    out.save(path("assets/ui", "icon_" + name + ".png"))


def icons():
    for n in ICON_NAMES:
        draw_icon(n)


def atlas():
    images = ["vignette", "panel", "dot"] + ["icon_" + n for n in ICON_NAMES]
    body = "".join(f'images {{\n  image: "/assets/ui/{n}.png"\n}}\n' for n in images)
    with open(path("assets/ui", "ui.atlas"), "w", newline="\n") as f:
        f.write(body + "margin: 2\nextrude_borders: 2\n")


def build_all():
    fonts_and_metrics()
    panel()
    dot()
    icons()
    atlas()


if __name__ == "__main__":
    build_all()
    print("ui fonts, metrics and atlas written")
