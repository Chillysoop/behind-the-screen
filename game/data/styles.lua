-- Campaign styles (A18): what kind of campaign this is, and where most of the time goes. At
-- Session Zero the table picks a style; cards are tagged by style and cross over through the
-- kinds of places that join styles (a port, a road, a stair, a door, a border). The DM can
-- change course in prep: ask the table, nudge with a gateway card, or force it with a story
-- event. From research into the 2024 DMG, published adventures (Ghosts of Saltmarsh, Dragon
-- Heist, Dungeon of the Mad Mage, Rime of the Frostmaiden, Descent into Avernus), The
-- Alexandrian, West Marches and Sly Flourish. Data only: tune freely. The model is
-- game/model/styles.lua.
--
-- A style: name, pitch, weights (scene mix, percent), home (base and haven), travel, rest,
--   fit (how each player type feels about it, -2..2), roles (each class's job here), tone,
--   settings, cross ({ to, via, card }: where it connects to other styles), starter (cards
--   that join the deck when it becomes home), behaviors (table habits in this style), gateway
--   (ask: the group-chat pitch and the replies; nudge: a card whose win changes course; force:
--   a story event that changes it).
-- cards: the styles' own cards (components.lua's fields, plus styles/cross/haven/gateway);
--   they join a campaign's deck when their style becomes home, or through a crossover.

