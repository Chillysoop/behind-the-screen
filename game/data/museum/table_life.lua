-- Table life for The Museum of Nightmares (game/model/table_life.lua): the small back-and-forth of a
-- real table, played in quiet moments. Adapted from "The Museum of Nightmares" by Luke Russell (DMs
-- Guild): the book told us what is in each room; every line here is our own words, and where the
-- book says little (the World of Tomorrow, the stairs), we made things up to fit.
--
-- curios: a friend pokes at something, a small die rolls on its own, and the DM answers by the total:
--   dull under 10, detail 10 to 16, lore 17 and up. A natural 20 or 1 hands the DM a quick card
--   (crit20: a small find, or a clue to the room's danger; crit1: a harmless mishap). Never a rules effect.
--   spot: a place on the room's board (game/data/map_library.lua places). who: the player types drawn to it.
--   react: what a friend says back, by the answer you gave (dull, detail, lore) or about the poking
--   itself (any); a line can carry a `when`. see: a line describing the thing first, when nothing else
--   has (the room's read-aloud, its board's places).
-- npc_questions: asking someone who's there; better on a good Persuasion or Insight roll. On a natural
--   20 or 1 the DM can improvise (people: each person's `slip`, what they let slip, and `misheard`).
-- scare: a natural 1's little scare in this room, in its own words (no lasting harm; never outside the
--   museum).
-- table_bits: the rest of the table's small business, told at the table. keepsake: a pocketed bit's name.
-- when: a condition (adventure.test), plus companion = id (that companion is along).

