-- Scene card components: what goes in the five slots on each scene card.
-- Data only: tune freely. They make up each campaign's story deck (game/model/deck.lua).
--
-- kind:       location, cast, goal, complication or reward.
-- cost:       prep hours to write it up properly (1 or 2).
-- fits:       scene types it suits; a fitting card raises scene quality.
-- tags:       what kind of fun it is (action, talk, explore, puzzle, lore,
--             loot, chaos, cozy, danger, mystery, heart, funny).
-- meters:     extra session meter gains for everyone.
-- difficulty: for cast and complications, 1 (easy) to 3 (hard).
-- thread:     a player key; advances that character's backstory thread. step: its place
--             in that thread (the notebook's Threads page).
-- line:       what gets narrated when the scene starts. again: the line when a recurring
--             card comes back (it remembers).
-- content:    Session Zero topics it touches (lines and veils): "kids", "spiders".
-- setting:    (locations) what kind of place it is: town, wild, indoor, outdoor, ruin, under,
--             high, water, crowd, bells, tavern, bridge. shop: somewhere to buy things.
-- where:      the card only happens at a location with one of these settings (no floor to
--             give way on a forest road). Cards without it fit anywhere.
-- alt:        a different line for the scene when the location has that setting.
-- skill:      (complications) the checks a hero makes to handle it.
-- reserve:    (M6) not in the deck. "inspiration" cards come from inspiration activities;
--             "payoff" cards turn up when their seed is ready to pay off (payoff_of).
--
-- The story deck (the slice rework):
-- deck:       how the card gets into a campaign's deck. "start": there from week 1 (the
--             default); "spare": joins when its kind runs short; "arc": this week's story beat
--             deals it (arc.lua); "follow": only when another card opens it.
-- recurring:  places and people come back after they've played (remembering what happened);
--             everything else is spent once it plays. foe: a fighting cast that's spent once
--             beaten. villain: spent once beaten, back again if they get away.
-- on:         what the card opens for the weeks ahead, by how its scene went:
--             { win = { ids }, lose = { ids }, played = { ids } }. Cards it opens join the
--             deck next week, marked new, saying which card they follow.
-- win, lose:  (goals) how the scene's big moment pays it off, named and specific. Fill-ins:
--             {cast}/{Cast}, {location}, {culprit}/{Culprit}, {secret}, {deal}.
-- got:        what the party walks away with, for the bridge to the next scene.
-- Casts: group (a crowd: "they are"), pronoun ("he", "she", "they", "it"), deal (what
-- they'll agree to), secret (what they're hiding, if they're the culprit), revered (you
-- don't threaten them: a mentor's ghost), talks = false (beasts).

